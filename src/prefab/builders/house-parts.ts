// Pip's furnishings return the original ordered parts; records own their solids and label references.
import { registerBuilder } from '../builders.ts';
import type { JsonObject } from '../types.ts';
import type { Part } from '../../render/part-geometry.ts';
declare module '../names.ts' {
  interface BuilderNames {
    'town.house-parts': true;
  }
}
const OAK = '#7f5630',
  PINE = '#a9794c',
  LEAF = '#5fa83a';
export function houseParts(p: JsonObject): { parts: Part[] } {
  const w = p.w as number,
    d = p.d as number;
  const DOOR = { w: 2.6 };
  switch (p.piece) {
    case 'floor':
      return {
        parts: Array.from({ length: 8 }, (_, k): Part => [
          'b',
          0,
          0.015,
          -d / 2 + (k + 0.5) * (d / 8),
          w - 0.3,
          0.03,
          d / 8 - 0.03,
          k % 2 ? '#c7a06e' : '#bb9360',
        ]),
      };
    case 'rug':
      return {
        parts: [
          ['c', 0, 0.04, 0.6, 1.9, 0.03, 1.9, '#b5533c'], // a rug
          ['c', 0, 0.05, 0.6, 1.5, 0.03, 1.5, '#d4a24e'],
        ],
      };
    case 'bed':
      return {
        parts: [
          ['b', -2.55, 0.25, -2.25, 1.6, 0.5, 2.5, OAK],
          ['b', -2.55, 0.55, -2.1, 1.5, 0.16, 2.2, '#3f6fb0'],
          ['s', -2.55, 0.68, -3.05, 0.55, 0.14, 0.32, '#f4f1e8'],
          ['b', -2.55, 0.65, -3.5, 1.6, 1.3, 0.12, OAK],
        ],
      };
    case 'desk':
      return {
        parts: [
          ['b', 1.6, 0.96, -2.0, 2.7, 0.1, 1.15, PINE],
          ['b', 0.45, 0.46, -2.0, 0.14, 0.92, 1.0, OAK],
          ['b', 2.75, 0.46, -2.0, 0.14, 0.92, 1.0, OAK],
        ],
      };
    case 'step':
      return { parts: [['b', 1.6, 0.19, -3.0, 0.8, 0.38, 0.7, '#8a6236']] };
    case 'leaf':
      return {
        parts: [
          ['s', 1.3, 1.04, -2.05, 0.62, 0.03, 0.42, LEAF],
          ['b', 1.3, 1.07, -2.05, 1.0, 0.01, 0.03, '#3f7a24'],
          ['c', 1.05, 1.08, -2.15, 0.08, 0.01, 0.08, '#c4453a'],
          ['c', 1.5, 1.08, -1.9, 0.08, 0.01, 0.08, '#c4453a'],
          ['c', 1.6, 1.08, -2.2, 0.08, 0.01, 0.08, '#c4453a'],
        ],
      };
    case 'filed':
      return {
        parts: [
          ['s', 2.3, 1.03, -2.2, 0.36, 0.02, 0.26, LEAF],
          ['s', 2.31, 1.06, -2.19, 0.36, 0.02, 0.26, '#6db345'],
          ['s', 2.29, 1.09, -2.2, 0.36, 0.02, 0.26, '#79be4e'],
        ],
      };
    case 'mug':
      return { parts: [['c', 2.38, 1.09, -1.72, 0.07, 0.14, 0.07, '#f4f1e8']] };
    case 'cabinet':
      return {
        parts: [
          ['b', 3.15, 0.75, -3.1, 0.8, 1.5, 0.8, '#6b7a78'],
          ['b', 3.15, 1.15, -2.69, 0.68, 0.34, 0.03, '#56625f'],
          ['b', 3.15, 0.75, -2.69, 0.68, 0.34, 0.03, '#56625f'],
          ['b', 3.15, 0.35, -2.69, 0.68, 0.34, 0.03, '#56625f'],
          ['s', 3.15, 1.2, -2.6, 0.26, 0.03, 0.14, LEAF],
        ],
      };
    case 'chair':
      return {
        parts: [
          ['b', -3.1, 0.3, 1.2, 0.8, 0.6, 0.8, '#8a2f28'],
          ['b', -3.46, 1.15, 1.2, 0.14, 1.9, 0.86, '#8a2f28'],
          ['s', -3.46, 2.15, 1.2, 0.12, 0.14, 0.43, '#d9a23a'],
        ],
      };
    case 'stove':
      return {
        parts: [
          ['c', 2.8, 0.55, 1.45, 0.5, 1.1, 0.5, '#2c2e33'],
          ['c', 2.8, 1.14, 1.45, 0.56, 0.06, 0.56, '#3f4145'],
          ['c', 2.8, 1.25, 1.45, 0.2, 0.2, 0.2, '#a9794c'],
        ],
      };
    case 'plant':
      return {
        parts: [
          ['c', 3.0, 0.2, 3.0, 0.24, 0.4, 0.24, '#b5533c'],
          ['s', 3.0, 0.75, 3.0, 0.42, 0.5, 0.42, LEAF],
        ],
      };
    case 'board':
      return {
        parts: [
          ['b', -0.2, 1.5, -3.2, 1.6, 1.15, 0.08, OAK],
          ['b', -0.2, 0.5, -3.25, 0.12, 1.0, 0.12, OAK],
        ],
      };
    case 'quilt':
      return {
        parts: [
          ['b', -2.55, 0.66, -1.6, 1.48, 0.08, 0.7, '#d4a24e'],
          ['b', -2.55, 0.71, -1.9, 1.48, 0.025, 0.06, '#fff0c9'],
          ['b', -2.55, 0.71, -1.3, 1.48, 0.025, 0.06, '#fff0c9'],
        ],
      };
    case 'drawers':
      return {
        parts: [
          ['b', 2.35, 0.7, -2.0, 0.6, 0.4, 0.98, OAK],
          ['b', 2.35, 0.74, -1.5, 0.52, 0.22, 0.025, PINE],
          ['b', 2.35, 0.74, -1.47, 0.18, 0.04, 0.04, '#d9a23a'],
        ],
      };
    case 'lamp':
      return {
        parts: [
          ['c', 0.6, 1.04, -2.25, 0.18, 0.06, 0.18, '#3f4145'],
          ['c', 0.6, 1.27, -2.25, 0.025, 0.42, 0.025, '#d9a23a'],
          ['s', 0.6, 1.51, -2.25, 0.3, 0.13, 0.17, '#3b7964'],
          ['b', 0.6, 1.44, -2.25, 0.45, 0.025, 0.23, '#fff0c9'],
        ],
      };
    case 'chair-trim':
      return {
        parts: [
          ['b', -3.1, 0.69, 0.86, 0.7, 0.14, 0.12, OAK],
          ['b', -3.1, 0.69, 1.54, 0.7, 0.14, 0.12, OAK],
          ['b', -3.05, 0.65, 1.2, 0.6, 0.12, 0.54, '#b5533c'],
        ],
      };
    case 'stove-trim':
      return {
        parts: [
          ['b', 2.8, 0.55, 1.93, 0.45, 0.48, 0.06, '#171d24'],
          ['b', 2.94, 0.56, 1.98, 0.06, 0.2, 0.05, '#d9a23a'],
          ['t', 2.8, 1.43, 1.45, 0.17, 0.16, 0.17, '#3f4145', Math.PI / 2],
        ],
      };
    case 'later-bridge':
      return {
        parts: [
          ['b', 0.72, 1.08, -1.8, 0.05, 0.14, 0.05, PINE],
          ['b', 1.02, 1.08, -1.8, 0.05, 0.14, 0.05, PINE],
          ['b', 0.87, 1.17, -1.8, 0.56, 0.03, 0.1, OAK],
        ],
      };
    case 'later-rail':
      return { parts: [['b', 1.3, 1.1, -2.0, 0.5, 0.05, 0.05, '#4c5058']] };
    case 'later-train':
      return {
        parts: [
          ['b', 3.15, 1.57, -3.1, 0.34, 0.14, 0.16, '#d8392b'],
          ['c', 3.26, 1.68, -3.1, 0.05, 0.1, 0.05, '#24262c'],
          ['b', -1.2, 0.27, 3.1, 0.9, 0.54, 0.34, '#8a6236'],
          ['b', -1.2, 0.58, 3.1, 0.3, 0.06, 0.06, '#3f4145'],
        ],
      };
    case 'later-mug':
      return { parts: [['c', 2.2, 1.09, -1.6, 0.07, 0.14, 0.07, '#d8392b']] };
    case 'mat':
      return { parts: [['b', 0, 0.02, d / 2 + 1.3, 1.5, 0.04, 0.9, '#8a6a48']] };
    case 'postbox':
      return {
        parts: [
          ['b', DOOR.w / 2 + 1.5, 0.55, d / 2 + 1.5, 0.12, 1.1, 0.12, OAK],
          ['b', DOOR.w / 2 + 1.5, 1.2, d / 2 + 1.5, 0.5, 0.36, 0.42, '#c4453a'],
        ],
      };
    case 'window-box':
      return {
        parts: [
          ['b', w / 2 + 0.18, 1.1, 0, 0.3, 0.2, 1.4, OAK],
          ['s', w / 2 + 0.2, 1.3, -0.4, 0.2, 0.18, 0.2, '#e4574a'],
          ['s', w / 2 + 0.2, 1.3, 0.05, 0.2, 0.18, 0.2, '#f0c030'],
          ['s', w / 2 + 0.2, 1.3, 0.45, 0.2, 0.18, 0.2, '#e4574a'],
        ],
      };
    case 'cabinet-pulls':
      return { parts: [0.35, 0.75, 1.15].map((y): Part => ['b', 3.15, y, -2.65, 0.23, 0.045, 0.055, '#d9a23a']) };
    default:
      throw new Error('house: unknown furnishing');
  }
}
registerBuilder('town.house-parts', houseParts);
